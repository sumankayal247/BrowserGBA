#!/usr/bin/env node
/**
 * Copies the emulator core runtime (mGBA compiled to WebAssembly) from
 * node_modules into `public/mgba/` so it is served verbatim, same-origin, and
 * untouched by the bundler.
 *
 * Why verbatim?  The threaded Emscripten runtime spawns its pthread worker with
 * `new Worker(new URL("mgba.js", import.meta.url))`.  If a bundler rewrote or
 * hashed that file, the worker URL would resolve to a path that does not exist,
 * so the core would fail to start.  Serving the pair from `public/` keeps
 * `import.meta.url` pointing at `/mgba/mgba.js`.
 *
 * The core is MPL-2.0 (see docs/THIRD_PARTY_NOTICES.md).  We do not modify it.
 */
import { createRequire } from 'node:module';
import { mkdir, copyFile, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'public', 'mgba');

/** Files that make up the shippable core runtime. */
const FILES = ['mgba.js', 'mgba.wasm'];

const NOTICE = `# Bundled emulator core

This directory is generated by \`npm run sync:core\` (scripts/sync-core.mjs).
Do not edit these files by hand.

- mGBA (Game Boy Advance emulator) — https://mgba.io/
  Copyright (c) 2013-2026 Jeffrey Pfau and contributors.
  Licensed under the Mozilla Public License 2.0 (MPL-2.0).
  WebAssembly build: https://github.com/thenick775/mgba (feature/wasm branch),
  published on npm as @thenick775/mgba-wasm.
  Corresponding source for the compiled binaries is available at the repository
  above; the MPL-2.0 requires that source remain available. We redistribute the
  unmodified compiled artifacts only.

The MPL-2.0 is a file-level copyleft licence: BrowserGBA's own source is MIT
licensed and lives outside this directory. See docs/THIRD_PARTY_NOTICES.md.
`;

async function main() {
  const pkgPath = require.resolve('@thenick775/mgba-wasm/package.json');
  const pkgDir = path.dirname(pkgPath);
  const pkg = require(pkgPath);

  await mkdir(outDir, { recursive: true });

  for (const file of FILES) {
    const from = path.join(pkgDir, 'dist', file);
    const to = path.join(outDir, file);
    await copyFile(from, to);
    const { size } = await stat(to);
    console.log(`  ${file.padEnd(12)} ${(size / 1024).toFixed(0).padStart(6)} KiB`);
  }

  // Record exactly which build we vendored so the compatibility matrix and any
  // future save-state compatibility check can reference a stable version.
  await writeFile(
    path.join(outDir, 'core-manifest.json'),
    JSON.stringify(
      {
        package: pkg.name,
        version: pkg.version,
        license: pkg.license,
        upstream: pkg.repository?.url ?? null,
        syncedAt: new Date().toISOString(),
        files: FILES,
      },
      null,
      2,
    ) + '\n',
  );
  await writeFile(path.join(outDir, 'NOTICE.md'), NOTICE);

  console.log(`Emulator core ${pkg.name}@${pkg.version} → public/mgba/`);
}

main().catch((error) => {
  console.error('Failed to sync emulator core:', error);
  process.exitCode = 1;
});
